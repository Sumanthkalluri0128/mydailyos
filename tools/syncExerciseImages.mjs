// Generates src/data/exerciseImages.ts from the WEB app's data/exerciseImages.js so the two can never drift.
// React Native needs every image as a static require(), so the file lists them one by one.
//   node tools/syncExerciseImages.mjs [path-to-web-exerciseImages.js]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const webFile = process.argv[2] || path.resolve(root, '../../web/client/src/data/exerciseImages.js');
const src = fs.readFileSync(webFile, 'utf8');

// Take the ROWS array literally from the web file (it is plain data), so there is one source of truth.
const m = src.match(/const ROWS = (\[[\s\S]*?\n\]);/);
if (!m) throw new Error('ROWS not found in ' + webFile);
const ROWS = Function(`"use strict"; return ${m[1]};`)();

// Same movement, different wording in the phone's plan (the phone's exercise names differ slightly from the web's).
// Only ever add a name that shows the SAME movement as the photo: a wrong photo is worse than the drawn figure.
const PHONE_NAMES = {
  'glute-bridge': ['Floor Glute Bridge'],
  'hip-thrust': ['Hip Thrust (Bench)'],
  'leg-curl': ['Lying Leg Curl', 'Leg Curl (Seated or Lying)'],
  'treadmill': ['Treadmill Walk', 'Brisk Walking (Outdoor)'],
  'cycling': ['Cycling (Stationary Bike)'],
};
for (const row of ROWS) if (PHONE_NAMES[row[0]]) row[2] = [...row[2], ...PHONE_NAMES[row[0]]];

const dir = path.join(root, 'assets', 'exercises');
const have = new Set(fs.readdirSync(dir).map((f) => f.replace(/\.webp$/, '')));
const used = new Set();
const rows = ROWS.map(([thumb, how, names, tips]) => {
  if (!have.has(thumb)) throw new Error(`missing assets/exercises/${thumb}.webp`);
  if (how && !have.has(how)) throw new Error(`missing assets/exercises/${how}.webp`);
  used.add(thumb); if (how) used.add(how);
  return [thumb, how, names, tips];
});

const files = [...used].sort();
const out = `// GENERATED by tools/syncExerciseImages.mjs from the web app's data/exerciseImages.js. Do not edit by hand:
// change the web file (or add a picture to assets/exercises/) and run the script again.
//
// Real photos for the exercises, cut from the four "Complete Exercise Library" sheets.
//   thumb  one clear picture (lists, live workout)
//   how    the step-by-step strip (4 frames with their step names), when the sheet has one
// An exercise gets its photo by NAME, so a different exercise never borrows a photo that shows another movement.
// No match = the drawn figure is used instead (utils/exerciseFigure.ts).
import type { ImageSourcePropType } from 'react-native';

export type ExercisePhoto = { thumb: ImageSourcePropType; how: ImageSourcePropType | null; tips: string[] };

const IMG: Record<string, ImageSourcePropType> = {
${files.map((f) => `  '${f}': require('../../assets/exercises/${f}.webp'),`).join('\n')}
};

// Row: [thumb, how | null, [names that show this photo], tips]
const ROWS: [string, string | null, string[], string[]][] = ${JSON.stringify(rows, null, 2)};

const norm = (s: unknown) => String(s || '').toLowerCase().replace(/[^a-z0-9]+/g, '');
const BY_NAME = new Map<string, ExercisePhoto>();
for (const [thumb, how, names, tips] of ROWS) {
  const rec: ExercisePhoto = { thumb: IMG[thumb], how: how ? IMG[how] : null, tips };
  for (const n of names) if (!BY_NAME.has(norm(n))) BY_NAME.set(norm(n), rec);
}

/** { thumb, how, tips } for an exercise (by name), or null when the sheets have no photo of that movement. */
export function photoFor(name?: string): ExercisePhoto | null {
  return name ? BY_NAME.get(norm(name)) || null : null;
}
export const hasPhoto = (name?: string) => !!photoFor(name);
/** Every exercise name that has a photo (for tests). */
export const PHOTO_NAMES: string[] = ROWS.flatMap((r) => r[2]);
`;
fs.writeFileSync(path.join(root, 'src', 'data', 'exerciseImages.ts'), out);
console.log(`exerciseImages.ts: ${rows.length} rows, ${files.length} images, ${PHOTO_COUNT(rows)} names`);
function PHOTO_COUNT(r) { return r.reduce((n, x) => n + x[2].length, 0); }
