import json,shutil,os,sys
SRC='/home/claude/stk3'; W='/home/claude/w/client'; M='/home/claude/m'
man=json.load(open(f'{SRC}/manifest.json'))
# web
dst=f'{W}/public/stickers'; shutil.rmtree(dst,ignore_errors=True); os.makedirs(dst)
for who in man: shutil.copytree(f'{SRC}/{who}',f'{dst}/{who}')
open(f'{W}/src/motion/stickerManifest.js','w').write('// Generated by tools/export_stickers.py — which stickers each character has: { who: { category: [[file, w, h], ...] } }\nexport default '+json.dumps(man,separators=(',',':'))+';\n')
json.dump({w:{c:[n for n,_,_ in l] for c,l in cs.items()} for w,cs in man.items()},open('/home/claude/w/server/data/stickerCatalog.json','w'),separators=(',',':'))
# mobile
dst=f'{M}/assets/stickers'; shutil.rmtree(dst,ignore_errors=True); os.makedirs(dst)
for who in man: shutil.copytree(f'{SRC}/{who}',f'{dst}/{who}')
lines=["// Generated by tools/export_stickers.py. Metro needs literal require() paths, so each sticker is spelled out.",
"export type Who = "+' | '.join(f"'{w}'" for w in man)+";",
"export type Sticker = { name: string; src: number; w: number; h: number };",
"export const STK: Record<Who, Record<string, Sticker[]>> = {"]
for who,cats in man.items():
    lines.append(f"  {who}: {{")
    for cat,items in cats.items():
        lines.append(f"    {cat}: [")
        for name,w,h in items: lines.append(f"      {{ name: '{name}', src: require('../../assets/stickers/{who}/{name}.webp'), w: {w}, h: {h} }},")
        lines.append("    ],")
    lines.append("  },")
lines.append("};")
open(f'{M}/src/motion/stickerImages.ts','w').write('\n'.join(lines)+'\n')
print({w:sum(len(v) for v in c.values()) for w,c in man.items()})
